import Foundation

/// `AppConfig` представляет собой централизованную модель конфигурации приложения.
/// Мы используем структуру, так как это Value Type, что обеспечивает безопасность при передаче
/// данных между различными слоями приложения.
///
/// ПРИНЦИП: Все "магические числа" приложения живут здесь, а не разбросаны по коду.
/// Это единственное место, где нужно менять параметры при тюнинге производительности.
public struct AppConfig: Codable, Equatable, Sendable {

    /// Глобальный синглтон для доступа к конфигурации.
    public static let shared = AppConfig()

    /// Максимальное число шагов оркестратора в одном reasoning loop.
    /// Ограничение защищает от бесконечных петель, если модель "зациклится" на инструментах.
    public let maxOrchestratorSteps: Int

    /// Максимальное число сообщений в истории чата, отправляемых в LLM.
    /// Ограничение защищает от превышения контекстного окна модели.
    public let maxHistoryMessages: Int

    /// Таймаут ожидания ответа от API в секундах.
    ///
    /// ПОЧЕМУ 300 СЕКУНД (5 минут):
    /// Стандартный таймаут URLSession — 60 секунд. Этого достаточно для простых запросов,
    /// но катастрофически мало для Чаппи, который в одном reasoning loop может выполнить
    /// десятки вызовов инструментов (чтение файлов, запись в память и т.д.), каждый из которых
    /// требует отдельного обращения к API. Сложные задачи — инспекция проекта, рефакторинг
    /// нескольких файлов — легко занимают 2-4 минуты. 5 минут — разумный потолок,
    /// который покрывает самые тяжёлые сценарии без риска вечного ожидания.
    public let requestTimeoutSeconds: TimeInterval

    /// Таймаут ожидания установки соединения с сервером в секундах.
    ///
    /// ПОЧЕМУ 30 СЕКУНД:
    /// Если соединение не устанавливается за 30 секунд — это явная сетевая проблема
    /// (сервер недоступен, нет интернета). Дальше ждать смысла нет.
    public let connectionTimeoutSeconds: TimeInterval

    /// Дефолтный инициализатор по умолчанию.
    private init() {
        self.maxOrchestratorSteps = 100
        self.maxHistoryMessages = 15
        self.requestTimeoutSeconds = 300
        self.connectionTimeoutSeconds = 30
    }
}
